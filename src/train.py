REPO = Path(__file__).resolve().parent.parent
DATA_RAW = REPO / "data" / "raw"
MODELS = REPO / "models"


# Training runs are numbered by what changed, not by date: phase 1 was the
# all-positive model that fired on everything, phase 2 added background
# negatives, phase 3 is the first trained on a capture-session split (the
# earlier splits scattered near-duplicates across train and test). Old run
# folders are kept, not overwritten — they are the evidence for the comparison.
RUN_NAME = "helopeltis_phase3"


def write_dataset_yaml() -> Path:
    """Write a data.yaml listing positives + negatives, as absolute path lists.

    Positives come from the capture-session split (`python -m src.data split`),
    NOT from the Roboflow train/valid/test folders. Those folders scatter photos
    taken seconds apart across all three splits, which makes the test set a
    near-duplicate of the training set and the resulting metrics meaningless.
    Missing split lists is a hard error rather than a fallback: silently
    training on the contaminated split is the exact failure this guards against.

    Ultralytics reads labels by swapping '/images/' -> '/labels/'. The negative
    folders hold empty label files, so those images act as background.
    """
    neg = DATA_RAW / "helopeltis_negatives"
    listings = {}

    for split in ("train", "valid", "test"):
        positives = MODELS / f"split_{split}.txt"
        if not positives.exists():
            raise SystemExit(
                f"Missing {positives.name}. Run `python -m src.data split` first "
                "— training on the Roboflow split would leak near-duplicates "
                "into the test set (see README, 'The split, and what it cost').")
        # splitlines(), not split(): repository paths can contain spaces.
        paths = [ln for ln in positives.read_text(encoding="utf-8").splitlines() if ln.strip()]

        neg_images = neg / split / "images"
        if neg_images.exists():
            paths += [str(p.resolve()).replace("\\", "/")
                      for p in sorted(neg_images.glob("*.jpg"))]
        elif split == "test":
            # On positives alone every image has a box, so precision there
            # cannot see a false positive.
            print("[warn] no test negatives — run `python -m src.data negatives --test`;"
                  " test precision will not be meaningful")
        else:
            print(f"[warn] no {split} negatives — run `python -m src.data negatives`")

        listing = MODELS / f"detector_{split}.txt"
        listing.write_text("\n".join(paths) + "\n", encoding="utf-8")
        listings[split] = str(listing.resolve()).replace("\\", "/")

    yaml_path = MODELS / "helopeltis_v2.yaml"
    yaml_path.write_text("\n".join([
        "# generated by src/train.py — capture-session split, positives + negatives",
        f"train: {listings['train']}",
        f"val: {listings['valid']}",
        f"test: {listings['test']}",
        "nc: 1",
        "names: ['Helopeltis']",
        "",
    ]), encoding="utf-8")
    return yaml_path


def scrub_onnx_paths(onnx_path: Path) -> bool:
    """Strip absolute filesystem paths out of the exported model's metadata.

    Ultralytics stamps the export with "trained on <absolute path to the data
    yaml>", i.e. a path from the machine that trained it, username included.
    Machine-specific and useless to anyone else. The model file is the one artifact that
    travels furthest (it is what a deployment loads), and a binary is the last
    place anyone thinks to grep, so this runs automatically on every export
    rather than being a step someone remembers.

    Returns True if anything was rewritten.
    """
    import re
    import onnx

    model = onnx.load(str(onnx_path))
    home = re.compile(r"[A-Za-z]:[\\/]Users[\\/][^\\/]+.*|/Users/[^/]+.*|/home/[^/]+.*")
    touched = False
    for prop in model.metadata_props:
        if home.search(prop.value):
            prop.value = home.sub("<path scrubbed>", prop.value)
            touched = True
    if touched:
        onnx.save(model, str(onnx_path))
        print(f"[scrub] removed absolute paths from {onnx_path.name} metadata")
    return touched


def train_detector(args):

    from ultralytics import YOLO

    if args.resume:
        last = MODELS / RUN_NAME / "weights" / "last.pt"
        print(f"Resuming from {last}\n")
        model = YOLO(str(last))
        model.train(resume=True)
    else:
        data_yaml = write_dataset_yaml()
        print(f"Dataset config: {data_yaml}\n")
        model = YOLO(args.weights)
        model.train(
            data=str(data_yaml),
            epochs=args.epochs,
            imgsz=args.imgsz,
            batch=args.batch,
            patience=args.patience,
            project=str(MODELS),
            name=RUN_NAME,
            exist_ok=True,
        )

    # Export ONNX at the size the fusion wrapper expects (320) and refresh the
    # model the pipeline actually loads.
    best = MODELS / RUN_NAME / "weights" / "best.pt"
    print(f"\nExporting ONNX from {best}")
    onnx_path = YOLO(str(best)).export(format="onnx", imgsz=320, opset=12)
    dst = MODELS / "helopeltis_damage.onnx"
    Path(onnx_path).replace(dst)
    scrub_onnx_paths(dst)
    print(f"Updated pipeline model -> {dst}")
    print("\nNext: re-run the specificity test to confirm false positives dropped.")



