"""Training — the three models this project ships.

    ``detector``  YOLOv8-n on tea-leaf FEEDING DAMAGE (not the insect). Trained
                  on positives plus background negatives, because without them
                  it fired on almost any image.
    ``flush``     MobileNetV2 on growth stage: tender shoot vs mature leaf. The
                  tender stage is the high-risk Helopeltis window — this is the
                  WHEN dimension, and what makes a risk score possible.
    ``insects``   MobileNetV2 on the bug itself. Two tasks: ``helopeltis``
                  (is it Helopeltis, another mirid, or something else) and
                  ``groups`` (ten insect groups mapped to ecological roles).

The two classifiers deliberately share one architecture and one training
procedure — frozen backbone, then a short full fine-tune with early stopping on
validation loss — so their numbers are comparable and there is one thing to
maintain rather than two.

Commands (from the repository root):

    python -m src.train detector [--epochs 60]
    python -m src.train flush
    python -m src.train insects --task helopeltis
    python -m src.train insects --task groups
"""
