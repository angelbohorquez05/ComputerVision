# --- Constants ---------------------------------------------------------------
# Index order defines the output logit order of the exported model; it must
# match FlushClassifier.FLUSH_CLASSES in src/pipeline.py.
FLUSH_CLASSES = ["new_flush", "mature_leaf"]

_ROOT = Path(__file__).resolve().parents[1]
FLUSH_DATA_DIR = _ROOT / "data" / "raw" / "flush_stages"
MODELS_DIR = _ROOT / "models"

IMG_SIZE = 224
# ImageNet normalization — must match the preprocessing in FlushClassifier.predict.
MEAN = [0.485, 0.456, 0.406]
STD = [0.229, 0.224, 0.225]
SEED = 42
_IMG_EXT = {".jpg", ".jpeg", ".png"}


def set_seed(seed: int = SEED) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


# --- Data --------------------------------------------------------------------
def gather_flush_samples(limit_per_class: int = 0) -> list[tuple[Path, int]]:
    """Return (path, label) pairs; label is the index of the class in FLUSH_CLASSES."""
    samples: list[tuple[Path, int]] = []
    for label, cls in enumerate(FLUSH_CLASSES):
        files = sorted(p for p in (FLUSH_DATA_DIR / cls).glob("*") if p.suffix.lower() in _IMG_EXT)
        if limit_per_class:
            files = files[:limit_per_class]
        samples.extend((p, label) for p in files)
    if not samples:
        raise SystemExit(f"No images found under {FLUSH_DATA_DIR}. Extract the dataset first.")
    return samples


class FlushDataset(Dataset):
    def __init__(self, items: list[tuple[Path, int]], tf: transforms.Compose):
        self.items = items
        self.tf = tf

    def __len__(self) -> int:
        return len(self.items)

    def __getitem__(self, i: int):
        path, label = self.items[i]
        img = Image.open(path).convert("RGB")
        return self.tf(img), label


train_tf = transforms.Compose([
    transforms.Resize((IMG_SIZE, IMG_SIZE)),
    transforms.RandomHorizontalFlip(),
    transforms.ColorJitter(0.2, 0.2, 0.2),
    transforms.ToTensor(),
    transforms.Normalize(MEAN, STD),
])
eval_tf = transforms.Compose([
    transforms.Resize((IMG_SIZE, IMG_SIZE)),
    transforms.ToTensor(),
    transforms.Normalize(MEAN, STD),
])


# --- Model -------------------------------------------------------------------
def build_model(num_classes: int = 2, freeze_backbone: bool = True) -> nn.Module:
    model = models.mobilenet_v2(weights=models.MobileNet_V2_Weights.IMAGENET1K_V1)
    if freeze_backbone:
        for p in model.features.parameters():
            p.requires_grad = False
    in_features = model.classifier[1].in_features
    model.classifier[1] = nn.Linear(in_features, num_classes)
    return model


def set_backbone_trainable(model: nn.Module, trainable: bool) -> None:
    for p in model.features.parameters():
        p.requires_grad = trainable


# --- Train / eval loops ------------------------------------------------------
def run_epoch(model, loader, criterion, optimizer=None) -> tuple[float, float]:
    training = optimizer is not None
    model.train(training)
    loss_sum = correct = total = 0
    for x, y in loader:
        if training:
            optimizer.zero_grad()
        with torch.set_grad_enabled(training):
            out = model(x)
            loss = criterion(out, y)
            if training:
                loss.backward()
                optimizer.step()
        loss_sum += loss.item() * x.size(0)
        correct += (out.argmax(1) == y).sum().item()
        total += x.size(0)
    return loss_sum / total, correct / total


def predict_all(model, loader) -> tuple[list[int], list[int]]:
    model.eval()
    ys, ps = [], []
    with torch.no_grad():
        for x, y in loader:
            ps.extend(model(x).argmax(1).tolist())
            ys.extend(y.tolist())
    return ys, ps


# --- Export ------------------------------------------------------------------
def export_onnx(model, path: Path) -> None:
    model.eval()
    dummy = torch.randn(1, 3, IMG_SIZE, IMG_SIZE)
    torch.onnx.export(
        model, dummy, str(path),
        input_names=["input"], output_names=["logits"],
        opset_version=13, dynamo=False,
    )


# --- Main --------------------------------------------------------------------
def train_flush(args) -> None:

    set_seed()
    MODELS_DIR.mkdir(exist_ok=True)
    torch.set_num_threads(max(1, (torch.get_num_threads())))

    # Capture-session split, 70/15/15, deterministic (no seed involved: the
    # assignment is a function of the filenames).
    #
    # NOT a stratified random split by image, which is what this used to do.
    # This dataset is burst photography — every timestamped photo in it has
    # another one within 60 seconds — so a random split puts near-duplicates of
    # the same leaf on both sides of the line and the test accuracy measures
    # recall, not generalisation. Sessions are kept whole and span both classes,
    # so a session's background and lighting can never be seen from both sides.
    samples = gather_flush_samples(args.limit)
    sessions = capture_groups([p.stem for p, _ in samples])
    # Stratify the session split by class: sessions here are mostly a single
    # stage, so a size-only split hands whole classes to one side (it once left
    # the test set with zero new_flush).
    stem_label = {p.stem: FLUSH_CLASSES[y] for p, y in samples}
    placement, _ = assign_sessions(sessions, ratios=(0.70, 0.15, 0.15), labels=stem_label)
    buckets = {"train": [], "valid": [], "test": []}
    for path, label in samples:
        buckets[placement[sessions[path.stem]]].append((path, label))
    train, val, test = buckets["train"], buckets["valid"], buckets["test"]

    n_sessions = len(set(sessions.values()))
    print(f"Split: train={len(train)}  val={len(val)}  test={len(test)} "
          f"({n_sessions} capture sessions kept whole)")
    for name, split in [("train", train), ("val", val), ("test", test)]:
        counts = {c: sum(1 for _, y in split if y == i) for i, c in enumerate(FLUSH_CLASSES)}
        print(f"  {name}: {counts}")
    if not (train and val and test):
        raise SystemExit("A split came out empty — check the session grouping.")

    dl = lambda items, tf, shuffle: DataLoader(
        FlushDataset(items, tf), batch_size=args.batch, shuffle=shuffle, num_workers=0)
    train_loader = dl(train, train_tf, True)
    val_loader = dl(val, eval_tf, False)
    test_loader = dl(test, eval_tf, False)

    model = build_model(num_classes=len(FLUSH_CLASSES), freeze_backbone=True)

    # Balanced class weights (mild imbalance ~53/47).
    counts = np.bincount([y for _, y in train], minlength=len(FLUSH_CLASSES))
    weights = torch.tensor((counts.sum() / (len(FLUSH_CLASSES) * counts)), dtype=torch.float32)
    criterion = nn.CrossEntropyLoss(weight=weights)
    print(f"Class weights: {weights.tolist()}")

    def train_phase(epochs, lr, label):
        params = [p for p in model.parameters() if p.requires_grad]
        opt = torch.optim.Adam(params, lr=lr)
        for e in range(1, epochs + 1):
            t0 = time.time()
            tr_loss, tr_acc = run_epoch(model, train_loader, criterion, opt)
            va_loss, va_acc = run_epoch(model, val_loader, criterion)
            print(f"[{label} {e}/{epochs}] "
                  f"train_loss={tr_loss:.3f} train_acc={tr_acc:.3f} | "
                  f"val_loss={va_loss:.3f} val_acc={va_acc:.3f} "
                  f"({time.time() - t0:.0f}s)")

    print("\n== Stage 1: head only (frozen backbone) ==")
    train_phase(args.epochs_head, args.lr, "head")

    if args.epochs_ft > 0:
        print("\n== Stage 2: full fine-tuning ==")
        set_backbone_trainable(model, True)
        train_phase(args.epochs_ft, args.ft_lr, "ft")

    # Final evaluation on the held-out test split.
    print("\n== Test set evaluation ==")
    ys, ps = predict_all(model, test_loader)
    report = classification_report(ys, ps, target_names=FLUSH_CLASSES, digits=3)
    cm = confusion_matrix(ys, ps).tolist()
    print(report)
    print(f"Confusion matrix (rows=true {FLUSH_CLASSES}): {cm}")

    # Persist weights + a small metrics summary for the model card.
    torch.save(model.state_dict(), MODELS_DIR / "flush_stage.pt")
    metrics = {
        "classes": FLUSH_CLASSES,
        "split": "capture session (70/15/15), sessions kept whole",
        "n_sessions": n_sessions,
        "n_train": len(train), "n_val": len(val), "n_test": len(test),
        "report": report, "confusion_matrix": cm,
    }
    (MODELS_DIR / "flush_stage_metrics.json").write_text(json.dumps(metrics, indent=2))
    print(f"\nSaved weights -> {MODELS_DIR / 'flush_stage.pt'}")

    if not args.no_export:
        onnx_path = MODELS_DIR / "flush_stage.onnx"
        export_onnx(model, onnx_path)
        print(f"Exported ONNX -> {onnx_path} (loaded by FlushClassifier)")




# ==========================================================================
# 3. Insect classifier - Helopeltis identity, or the ten groups
# ==========================================================================

# Stronger augmentation than the flush classifier's, and defined HERE rather
# than reusing its `train_tf`: that transform is tuned for leaf photos and is
# shared with a trained model, so editing it would silently change what the
# flush classifier learns.
#
# The first run overfitted hard (train 0.92 vs val 0.64). Random crops and
# rotation attack exactly that: the iNaturalist photos are all well-framed
# portraits, so without them the model can memorise composition instead of
# learning what the insect looks like.
family_train_tf = transforms.Compose([
    transforms.RandomResizedCrop(IMG_SIZE, scale=(0.6, 1.0), ratio=(0.8, 1.25)),
    transforms.RandomHorizontalFlip(),
    transforms.RandomRotation(15),
    transforms.ColorJitter(0.3, 0.3, 0.3, 0.05),
    transforms.ToTensor(),
    transforms.Normalize(MEAN, STD),
])

DATA_DIR = _ROOT / "data" / "raw" / "insect_families"

CLASSES = [cls for _q, cls, _role in GROUPS]
ROLE_OF = {cls: role for _q, cls, role in GROUPS}

# --- Tasks -------------------------------------------------------------------
# `groups`     the ten insect groups — a general WHO, family level.
# `helopeltis` the question the project actually needs: is this Helopeltis?
#              Three classes, because the only hard boundary is against other
#              mirids; separating it from a bee is free.
#
# The `miridae` folder is deliberately absent from the helopeltis task: it was
# downloaded at family level, so it may contain Helopeltis (1 of 150 did) and
# would put the target on both sides of the boundary. `other_miridae` replaces
# it, downloaded with the genus explicitly excluded.
#
# A fourth-class variant trained directly on ecological roles was tried and
# dropped — it scored 0.667 against 0.760 for aggregating this model's
# predictions, because "pest" lumps together insects that look nothing alike.
TASK_CLASSES = {
    "groups": CLASSES,
    "helopeltis": ["helopeltis", "other_miridae", "other_insects"],
}
TASK_FOLDERS = {
    "groups": {c: c for c in CLASSES},
    "helopeltis": {
        "helopeltis": "helopeltis",
        "other_miridae": "other_miridae",
        **{c: "other_insects" for c in CLASSES if c != "miridae"},
    },
}


def gather_insect_samples(limit_per_class: int = 0,
                   task: str = "groups") -> tuple[list[tuple[Path, int]], list[str]]:
    """Return ((path, class_index) pairs, class names) for the chosen task."""
    classes = TASK_CLASSES[task]
    samples: list[tuple[Path, int]] = []
    for folder, cls in TASK_FOLDERS[task].items():
        files = sorted(p for p in (DATA_DIR / folder).glob("*") if p.suffix.lower() in _IMG_EXT)
        if limit_per_class:
            files = files[:limit_per_class]
        samples.extend((p, classes.index(cls)) for p in files)
    if not samples:
        raise SystemExit(f"No images under {DATA_DIR}. Run: python -m src.build_families")
    return samples, classes


def helopeltis_binary(y_true: list[int], y_pred: list[int],
                      classes: list[str]) -> dict:
    """Precision/recall for Helopeltis against everything else.

    The headline for this task. Three-class accuracy hides what matters: a
    Helopeltis called `other_miridae` is a miss on the target, while one called
    `other_insects` is the same miss but easier to forgive. Both are false
    negatives here — and `hard_confusions` counts how many of the errors are
    against the other mirids, which is the boundary that decides whether the
    model learned the insect or just "bug on a leaf".
    """
    h = classes.index("helopeltis")
    tp = sum(t == h and p == h for t, p in zip(y_true, y_pred))
    fp = sum(t != h and p == h for t, p in zip(y_true, y_pred))
    fn = sum(t == h and p != h for t, p in zip(y_true, y_pred))
    mir = classes.index("other_miridae")
    return {
        "precision": round(tp / (tp + fp), 4) if tp + fp else 0.0,
        "recall": round(tp / (tp + fn), 4) if tp + fn else 0.0,
        "true_positives": tp, "false_positives": fp, "false_negatives": fn,
        "missed_as_other_miridae": sum(t == h and p == mir for t, p in zip(y_true, y_pred)),
        "other_miridae_called_helopeltis": sum(t == mir and p == h
                                               for t, p in zip(y_true, y_pred)),
    }


def role_accuracy(y_true: list[int], y_pred: list[int], classes: list[str]) -> float:
    """Accuracy at the level that actually drives a decision.

    Confusing Coreidae with Cicadellidae costs a grower nothing — both are pests
    and the action is the same. Confusing a pest with a pollinator is the error
    that matters: it means spraying something that was helping. So the honest
    headline is agreement on the ROLE, not on the exact group.

    Only defined for the ten-group task; the helopeltis task reports
    `helopeltis_binary` instead.
    """
    hits = sum(ROLE_OF[classes[t]] == ROLE_OF[classes[p]] for t, p in zip(y_true, y_pred))
    return hits / len(y_true) if y_true else 0.0


def train_insects(args) -> None:

    set_seed()
    samples, classes = gather_insect_samples(args.limit, task=args.task)
    labels = [y for _p, y in samples]
    stem = "helopeltis_id" if args.task == "helopeltis" else "insect_families"

    counts = Counter(labels)
    print(f"{len(samples)} images across {len(classes)} "
          f"classes ({args.task} task)")
    for i, cls in enumerate(classes):
        detail = f" {ROLE_OF[cls]:11s}" if args.task == "groups" else ""
        print(f"  {cls:16s}{detail} {counts.get(i, 0):4d}")
    thin = [classes[i] for i in range(len(classes)) if counts.get(i, 0) < 30]
    if thin:
        print(f"\n[warn] under 30 images: {', '.join(thin)} — treat their metrics as noise")

    # Stratified 70/15/15, deterministic — same protocol as the flush classifier.
    # Stratifying twice needs >= 4 images in the rarest class; below that sklearn
    # raises. A thin class is a data problem, not a reason to crash, so fall back
    # to an unstratified split and say so — the metrics are noise either way.
    stratify_ok = min(counts.values()) >= 4 and len(counts) == len(classes)
    if not stratify_ok:
        print("[warn] a class is too thin to stratify — splitting unstratified")
    train, temp = train_test_split(samples, test_size=0.30, random_state=SEED,
                                   stratify=labels if stratify_ok else None)
    temp_labels = [y for _p, y in temp]
    temp_ok = stratify_ok and min(Counter(temp_labels).values()) >= 2
    val, test = train_test_split(temp, test_size=0.50, random_state=SEED,
                                 stratify=temp_labels if temp_ok else None)
    print(f"\nsplit: train {len(train)} | val {len(val)} | test {len(test)}")

    loaders = {
        "train": DataLoader(FlushDataset(train, family_train_tf), batch_size=args.batch,
                            shuffle=True),
        "val":   DataLoader(FlushDataset(val, eval_tf), batch_size=args.batch),
        "test":  DataLoader(FlushDataset(test, eval_tf), batch_size=args.batch),
    }

    model = build_model(num_classes=len(classes), freeze_backbone=True)

    # Inverse-frequency class weights: iNaturalist has far more bee photos than
    # mirid photos, and the rare classes here are the ones we care about.
    train_counts = np.bincount([y for _p, y in train], minlength=len(classes))
    weights = torch.tensor(train_counts.sum() / (len(classes) * np.maximum(train_counts, 1)),
                           dtype=torch.float32)
    criterion = nn.CrossEntropyLoss(weight=weights)

    # Early stopping on validation loss, with the best weights restored at the
    # end. Without it the previous run's last epoch was pure memorisation:
    # train accuracy climbed to 0.92 while val loss had already turned upward.
    # `best` is tracked across BOTH phases, so fine-tuning can only keep weights
    # that actually beat the frozen-backbone stage.
    best = {"loss": float("inf"), "state": copy.deepcopy(model.state_dict()), "tag": "init"}
    history = []

    def run_phase(tag, epochs, optimizer):
        stale = 0
        for ep in range(epochs):
            tl, ta = run_epoch(model, loaders["train"], criterion, optimizer)
            vl, va = run_epoch(model, loaders["val"], criterion)
            improved = vl < best["loss"] - 1e-4
            if improved:
                best.update(loss=vl, state=copy.deepcopy(model.state_dict()),
                            tag=f"{tag} {ep+1}")
                stale = 0
            else:
                stale += 1
            history.append({"phase": tag, "epoch": ep + 1, "train_loss": round(tl, 4),
                            "train_acc": round(ta, 4), "val_loss": round(vl, 4),
                            "val_acc": round(va, 4), "improved": improved})
            print(f"[{tag:4s} {ep+1}/{epochs}] train {tl:.3f}/{ta:.3f}  "
                  f"val {vl:.3f}/{va:.3f}{'  *' if improved else ''}")
            if stale >= args.patience:
                print(f"       early stop: {stale} epochs without improvement")
                return

    opt = torch.optim.Adam([p for p in model.parameters() if p.requires_grad], lr=args.lr)
    run_phase("head", args.epochs_head, opt)

    set_backbone_trainable(model, True)
    opt = torch.optim.Adam(model.parameters(), lr=args.ft_lr)
    run_phase("ft", args.epochs_ft, opt)

    print(f"\nRestoring best weights: {best['tag']} (val loss {best['loss']:.3f})")
    model.load_state_dict(best["state"])

    y_true, y_pred = predict_all(model, loaders["test"])
    group_acc = sum(t == p for t, p in zip(y_true, y_pred)) / len(y_true)
    is_groups = args.task == "groups"
    role_acc = role_accuracy(y_true, y_pred, classes) if is_groups else None
    binary = None if is_groups else helopeltis_binary(y_true, y_pred, classes)

    print("\n" + "=" * 60)
    print(f"Overall accuracy : {group_acc:.3f}  (exact class)")
    if is_groups:
        print(f"Role accuracy    : {role_acc:.3f}  (pest / beneficial / pollinator / neutral)")
    else:
        print(f"HELOPELTIS       : precision {binary['precision']:.3f}  recall {binary['recall']:.3f}")
        print(f"  missed as another mirid      : {binary['missed_as_other_miridae']}/{binary['true_positives'] + binary['false_negatives']}")
        print(f"  other mirids called Helopeltis: {binary['other_miridae_called_helopeltis']}")
    print("=" * 60)
    # labels= is required: a tiny test split may not contain every class, and
    # without it sklearn silently reports on a shorter name list.
    all_labels = list(range(len(classes)))
    print(classification_report(y_true, y_pred, labels=all_labels,
                                target_names=classes, zero_division=0))

    # A --limit run is a smoke test on a handful of images. Letting it write to
    # the real artifact paths silently replaces a trained model and its metrics
    # with numbers measured on ~15 test images — which is exactly what happened
    # once. Smoke runs print and exit instead.
    if args.limit:
        print(f"\n[smoke run: --limit {args.limit}] artifacts NOT saved — "
              f"{stem}.pt / _metrics.json left untouched")
        return

    MODELS_DIR.mkdir(exist_ok=True)
    torch.save(model.state_dict(), MODELS_DIR / f"{stem}.pt")
    metrics = {
        "task": args.task,
        "classes": classes,
        "roles": ROLE_OF,
        "n_images": len(samples),
        "n_test": len(test),
        "group_accuracy": round(group_acc, 4),
        "role_accuracy": round(role_acc, 4) if role_acc is not None else None,
        "helopeltis": binary,
        "best_epoch": best["tag"],
        "best_val_loss": round(best["loss"], 4),
        "history": history,
        "augmentation": "RandomResizedCrop(0.6-1.0) + flip + rotation(15) + jitter(0.3)",
        "per_class": classification_report(y_true, y_pred, labels=all_labels,
                                           target_names=classes, zero_division=0,
                                           output_dict=True),
        "confusion_matrix": confusion_matrix(y_true, y_pred, labels=all_labels).tolist(),
        "caveat": ("iNaturalist photos: one insect, large and centred. Does not "
                   "measure performance on field photos, and cannot separate "
                   "Helopeltis from other Miridae."),
    }
    (MODELS_DIR / f"{stem}_metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")

    if not args.no_export:
        export_onnx(model, MODELS_DIR / f"{stem}.onnx")

    print(f"\nSaved -> models/{stem}.pt + {stem}_metrics.json")




